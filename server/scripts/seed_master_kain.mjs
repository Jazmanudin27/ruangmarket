export async function runMigration(pool) {
  console.log('[Migrasi] 1. Buat tabel master_kain jika belum ada...');
  await pool.query(`
    CREATE TABLE IF NOT EXISTS master_kain (
      id INT AUTO_INCREMENT PRIMARY KEY,
      kode_perusahaan VARCHAR(32) DEFAULT 'RSG',
      kode_sku_kain VARCHAR(64) NOT NULL UNIQUE,
      nama_kain VARCHAR(150) NOT NULL,
      jenis_kain VARCHAR(100) NULL,
      warna VARCHAR(100) NULL,
      satuan VARCHAR(32) DEFAULT 'METER',
      stok_kain DECIMAL(15,2) DEFAULT 0,
      harga_per_meter DECIMAL(15,2) DEFAULT 0,
      keterangan TEXT NULL,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      INDEX idx_kode_sku_kain (kode_sku_kain),
      INDEX idx_kode_perusahaan (kode_perusahaan)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Master Data Kain ERP RuangMarket';
  `);

  console.log('[Migrasi] 2. Tambah kolom sku_kain di produk_master jika belum ada...');
  try {
    await pool.query(`ALTER TABLE produk_master ADD COLUMN sku_kain VARCHAR(64) NULL`);
    console.log('[Migrasi] Kolom sku_kain berhasil ditambahkan ke produk_master.');
  } catch (e) {
    if (!e.message.includes('Duplicate column')) {
      console.warn('[Migrasi Info]:', e.message);
    }
  }

  try {
    await pool.query(`ALTER TABLE produk_master ADD INDEX idx_sku_kain (sku_kain)`);
  } catch (e) {}

  // Parse mappings
  const lines = RAW_MAPPING.trim().split('\n').map(l => l.trim()).filter(Boolean);
  const mappings = [];
  const uniqueKainSet = new Set();

  for (const line of lines) {
    const parts = line.split(/\t+|\s{2,}/);
    if (parts.length >= 2) {
      const prodSku = parts[0].trim();
      const kainSku = parts[1].trim();
      mappings.push({ prodSku, kainSku });
      uniqueKainSet.add(kainSku);
    }
  }

  console.log(`[Migrasi] Terdeteksi ${uniqueKainSet.size} jenis SKU Kain unik dan ${mappings.length} baris relasi produk.`);

  // 3. Masukkan ke tabel master_kain
  console.log('[Migrasi] 3. Menyimpan data master_kain...');
  for (const kainSku of uniqueKainSet) {
    const info = getKainMetadata(kainSku);
    await pool.query(`
      INSERT INTO master_kain (
        kode_perusahaan, kode_sku_kain, nama_kain, jenis_kain, warna, satuan, stok_kain, harga_per_meter
      ) VALUES (?, ?, ?, ?, ?, 'METER', 0, ?)
      ON DUPLICATE KEY UPDATE
        nama_kain = VALUES(nama_kain),
        jenis_kain = VALUES(jenis_kain),
        warna = VALUES(warna),
        harga_per_meter = VALUES(harga_per_meter)
    `, ['RSG', kainSku, info.nama, info.jenis, info.warna, info.harga || 25000]);
  }
  console.log('[Migrasi] Berhasil menyimpan semua data master_kain!');

  // 4. Update relasi sku_kain di produk_master
  console.log('[Migrasi] 4. Update SKU Kain ke produk_master...');
  let updatedCount = 0;
  let insertedCount = 0;

  for (const m of mappings) {
    // Coba update pada kode_sku persis atau kode_sku dengan prefix RSG-
    const [res] = await pool.query(`
      UPDATE produk_master 
      SET sku_kain = ? 
      WHERE kode_sku = ? OR kode_sku = ?
    `, [m.kainSku, m.prodSku, `RSG-${m.prodSku}`]);

    if (res.affectedRows > 0) {
      updatedCount += res.affectedRows;
    } else {
      // Jika produk belum ada di produk_master, tambahkan baris produk dasar agar mapping tersimpan
      try {
        const info = getKainMetadata(m.kainSku);
        await pool.query(`
          INSERT INTO produk_master (
            kode_perusahaan, kode_sku, nama_produk, kategori, satuan,
            harga_jual, harga_modal, stok_fisik, status, status_order,
            tipe_set, estimasi_kain, sku_kain
          ) VALUES (?, ?, ?, ?, 'PCS', 0, 0, 0, 'Aktif', 'Ready Stok', 'Single', ?, ?)
          ON DUPLICATE KEY UPDATE sku_kain = VALUES(sku_kain)
        `, ['RSG', m.prodSku, `Produk ${m.prodSku}`, 'Pakaian', info.nama, m.kainSku]);
        insertedCount++;
      } catch (insertErr) {
        console.warn(`[Migrasi Warning] Gagal insert skeleton untuk ${m.prodSku}:`, insertErr.message);
      }
    }
  }

  console.log(`[Migrasi Selesai] Total ${updatedCount} produk diperbarui sku_kain, ${insertedCount} produk baru di-insert dengan sku_kain.`);
}

